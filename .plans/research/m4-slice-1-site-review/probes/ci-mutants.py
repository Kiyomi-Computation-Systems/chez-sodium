import shutil, os, sys
src = '.github/workflows'
root = 'build/m4s1-review-site/ci'
def mk(name):
    d = os.path.join(root, name)
    if os.path.exists(d): shutil.rmtree(d)
    shutil.copytree(src, d, symlinks=True)
    return d
def rd(d, f): return open(os.path.join(d, f), encoding='utf-8', newline='').read()
def wr(d, f, t): open(os.path.join(d, f), 'w', encoding='utf-8', newline='').write(t)
def ed(d, f, old, new, count=1):
    t = rd(d, f); assert t.count(old) == count, (f, old, t.count(old)); wr(d, f, t.replace(old, new))
